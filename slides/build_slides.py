"""Build a standalone slides/index.html from the deck source in slides/source/.

The source files (deck.json, deck.css, slides/*.html) are the deck as published
in the Claude Slides viewer. That viewer supplies custom elements (<x-connector>,
<x-icon>) and hosts the images; this script swaps those for plain HTML/CSS and
repo-relative image paths so the deck opens in any browser.

Usage:  python slides/build_slides.py
"""
import html
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "source"

# Images uploaded to the viewer, mapped to the same files in this repo
# (matched by SHA-256).
IMAGES = {
    "/_blob/ccc53e2a2ea35a1e1e4cfea07e80232d": "../images/results/parity%20plots.png",
    "/_blob/d19de61b91a93484759c8d8ffdfbf493": "../images/thesis_figures/Figure_IV_7_Cation_Boxplot.png",
}

ARROW = (
    '<div class="arrow-sa" aria-hidden="true">'
    '<svg viewBox="0 0 48 24" width="48" height="24">'
    '<line x1="0" y1="12" x2="40" y2="12" stroke="currentColor" stroke-width="4"/>'
    '<path d="M36 4 L46 12 L36 20" fill="none" stroke="currentColor" stroke-width="4"/>'
    "</svg></div>"
)
LOOP_ICON = (
    '<svg class="loop-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M22 12h-4l-3 9L9 3l-3 9H2"/></svg>'
)

EXTRA_CSS = """
html, body { margin: 0; background: #1b1f22; }
.deck { display: flex; flex-direction: column; align-items: center; gap: 24px; padding: 24px 0; }
.frame { width: calc(min(100vw - 32px, 1600px)); aspect-ratio: 16 / 9; position: relative; overflow: hidden;
         box-shadow: 0 4px 24px rgba(0,0,0,.4); }
.frame > section { position: absolute; top: 0; left: 0; width: 1920px; height: 1080px; transform-origin: 0 0; }
.arrow-sa { width: 48px; align-self: center; color: var(--teal); display: flex; flex: none; }
aside { display: none; }
.notes { width: calc(min(100vw - 32px, 1600px)); color: #c9d1d3; font: 15px/1.5 Inter, Arial, sans-serif; margin: -12px 0 8px; }
.notes summary { cursor: pointer; color: #8fb8b2; }
@media print {
  html, body { background: none; }
  .deck { padding: 0; gap: 0; }
  .frame { width: 100vw; box-shadow: none; break-after: page; }
  .notes { display: none; }
  @page { size: 1920px 1080px; margin: 0; }
}
"""

SCALE_JS = """
function fit(){document.querySelectorAll('.frame').forEach(f=>{
  f.firstElementChild.style.transform='scale('+(f.clientWidth/1920)+')';});}
addEventListener('resize',fit);addEventListener('load',fit);fit();
"""


def convert(slide: str) -> str:
    slide = re.sub(r"<x-connector[^>]*>\s*</x-connector>", ARROW, slide)
    slide = re.sub(r'<x-icon[^>]*class="loop-icon"[^>]*>\s*</x-icon>', LOOP_ICON, slide)
    for blob, path in IMAGES.items():
        slide = slide.replace(f'src="{blob}"', f'src="{path}"')
    return slide


def main() -> None:
    deck = json.loads((SRC / "deck.json").read_text(encoding="utf-8"))
    css = (SRC / "deck.css").read_text(encoding="utf-8")
    fonts = "".join(
        f'<link rel="stylesheet" href="{html.escape(f["href"])}">\n'
        for f in deck.get("faces", {}).values()
    )
    parts = []
    for sid in deck["order"]:
        raw = (SRC / "slides" / f"{sid}.html").read_text(encoding="utf-8")
        body = convert(raw)
        parts.append(f'<div class="frame">{body}</div>')
        m = re.search(r"<aside>(.*?)</aside>", raw, re.S)
        if m:
            parts.append(
                f'<details class="notes"><summary>Speaker notes</summary>{m.group(1)}</details>'
            )
    title = html.escape(deck.get("title", "Slides"))
    out = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
{fonts}<style>
{css}
{EXTRA_CSS}
</style>
</head>
<body>
<!-- Generated by slides/build_slides.py from slides/source/. Do not edit by hand. -->
<main class="deck">
{chr(10).join(parts)}
</main>
<script>{SCALE_JS}</script>
</body>
</html>
"""
    (HERE / "index.html").write_text(out, encoding="utf-8")
    print(f"Wrote {HERE / 'index.html'} ({len(deck['order'])} slides)")


if __name__ == "__main__":
    main()
